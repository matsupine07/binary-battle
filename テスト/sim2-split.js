// ============================================================
// シミュレーション2：分割ルールを入れたらどうなるか
//
// 検証した仕様
//   ・自分の番に、攻撃の代わりに両手の指を分け直す（合計は保つ）
//   ・死んだ手は分割に使えない（復活を防ぐ）
//   ・両手とも 1〜30（0も31も作れない＝自滅もパスも防ぐ）
//   ・左右を入れ替えただけの分割は禁止（盤面が実質変わらない＝ルールにないパスになる）
//
// 結果（2026-07-27）：**逆効果。不採用。**
//   ランダム打ちで 73.5手 → 220.7手 と3倍に伸びた。
//   理由＝分割は誰にもダメージを与えないので、1手使って盤面が決着に近づかない。
//   上手い打ち手（狙える形を作る分割を優先）でようやく現状と同等。
//   つまり「初心者ほど損をする」設計になってしまう。
//
// ★この実験の価値★
//   UIを1行も書く前に却下できた。
//   分け方は最大29通りあるので、ボタン配置から作っていたら数時間かかっていた。
// ============================================================

const { verify, runMany, line } = require("./sim-common");

verify();

console.log("■ 分割ルールの効果（各2万回・打ち切り10,000手）");
console.log("");
console.log("  --- ランダムに打つ（初心者に近い） ---");
line("分割ナシ（現状）", runMany({ max: 31, strategy: "random" }),               true);
line("分割アリ",         runMany({ max: 31, strategy: "random", split: true }),  true);
console.log("");
console.log("  --- 殺せるなら殺す（慣れた人に近い） ---");
line("分割ナシ（現状）", runMany({ max: 31, strategy: "greedy" }),               true);
line("分割アリ",         runMany({ max: 31, strategy: "greedy", split: true }),  true);
console.log("");
console.log("  --- 殺せるなら殺す＋狙える形を作る分割を優先 ---");
line("分割アリ・賢い",   runMany({ max: 31, strategy: "smart",  split: true }),  true);
console.log("");
console.log("  ※1つの打ち手だけで測っていたら誤判断していた。");
console.log("    ランダムだけなら「論外」、上手い打ち手だけなら「悪くない」と見える。");
console.log("    両方測ったから「初心者ほど損をする」という正しい理由で却下できた。");
