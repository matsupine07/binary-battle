// ============================================================
// シミュレーション1：バランス実測（元ゲーム vs 二進数版）
//
// 仕様書に前から書いてあった懸念
//   「31ぴったりは5ぴったりより出しにくいので、決着がつきにくいのでは」
// を数字で確かめる。
//
// 結果（2026-07-27）：
//   ・手数は約7倍かかる                        → 懸念は当たり
//   ・でも無限ループ率は二進数版のほうが“低い”  → 懸念は逆
//   ・打ち切りを100倍にしても決着率が動かない    → 未決着は本物の無限ループ
//     → ここから「画面版に引き分け処理が無い」という実害が見つかった
//
// ★2026-08-06 訂正：上の2行目には「打ち手」の条件が抜けていた。
//   “低い”のは random（初心者同士）のときだけ。greedy（殺せるなら殺す）では逆転する。
//     random … 元 85.06% ／ 二進 96.56%  → 決着しにくいのは元ゲーム
//     greedy … 元 99.13% ／ 二進 95.17%  → 決着しにくいのは二進数版
//   README の落とし穴 #3（1つの打ち手だけで結論を出さない）に自分で該当していた。
//   詳細は ../仕様書.md の「記事ネタ → バランス検証編」に記録。
// ============================================================

const { verify, runMany, line } = require("./sim-common");

verify();

console.log("■ 元ゲーム vs 二進数版（各2万回・打ち切り10,000手）");
console.log("");
console.log("  --- ランダムに打つ（初心者に近い） ---");
line("元ゲーム（上限5）",   runMany({ max: 5,  strategy: "random" }));
line("二進数版（上限31）",  runMany({ max: 31, strategy: "random" }));
console.log("");
console.log("  --- 殺せるなら殺す（慣れた人に近い） ---");
line("元ゲーム（上限5）",   runMany({ max: 5,  strategy: "greedy" }));
line("二進数版（上限31）",  runMany({ max: 31, strategy: "greedy" }));

console.log("");
console.log("");
console.log("■ 未決着は「長いだけ」か「本当に終わらない」か");
console.log("   打ち切りを100倍にしても決着率が変わらなければ、本物の無限ループ");
console.log("");
for (const cap of [1000, 10000, 100000]) {
  console.log("  --- 打ち切り " + cap.toLocaleString() + " 手 ---");
  line("元ゲーム（上限5）",  runMany({ max: 5,  strategy: "random", cap: cap, games: 5000 }));
  line("二進数版（上限31）", runMany({ max: 31, strategy: "random", cap: cap, games: 5000 }));
  console.log("");
}
