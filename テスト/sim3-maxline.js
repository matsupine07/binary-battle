// ============================================================
// シミュレーション3：死亡ライン（上限）を変えるとどうなるか
//
// パート1：指の本数を変える案（3本=7 / 4本=15 / 5本=31）
//   → 短くはなるが、「手の指5本＝二進数5桁」という核が崩れるので不採用。
//     ※指4本（上限15）は最悪の選択。短くなる代わりに決着率が一番低い。
//
// パート2：上限を3〜40まで全部試す
//   → ★未解明★ 決着率が不規則に暴れる。
//     100%になるのは 3, 4, 6, 7, 9, 14, 23, 27 だけで、間の値は55〜96%とばらつく。
//     「素数だと決着しやすいのでは」という仮説を立てたが、データは支持しなかった
//     （13・17・29は素数なのに低く、4・6・9・14・27は合成数なのに100%）。理由は不明。
//     このゲームの正体は mod（上限）の足し算（死亡＝0になること）なので、数論の問題。
//
// パート3：100%が本物か、回数と打ち切りを大きくして確かめる
//   → 5万回・打ち切り2万手でも、きっかり100.000%。試行回数の問題ではなく構造的な性質。
// ============================================================

const { verify, runMany, line } = require("./sim-common");

verify();

// ---- パート1：指の本数 ----------------------------------------------
const COUNTS = [
  ["指3本（親・人・中／上限7）",   7],
  ["指4本（＋薬指／上限15）",     15],
  ["指5本（現状／上限31）",       31],
  ["元ゲーム（上限5）・参考",      5],
];

console.log("■ パート1：指の本数を変える（各2万回）");
console.log("");
console.log("  --- ランダムに打つ ---");
for (const [label, max] of COUNTS) line(label, runMany({ max: max, strategy: "random" }));
console.log("");
console.log("  --- 殺せるなら殺す ---");
for (const [label, max] of COUNTS) line(label, runMany({ max: max, strategy: "greedy" }));

// ---- パート2：上限を3〜40まで全部 -------------------------------------
const isPrime = n => { for (let i = 2; i * i <= n; i++) if (n % i === 0) return false; return n > 1; };

console.log("");
console.log("");
console.log("■ パート2：上限を3〜40まで全部試す（各5,000回・ランダム打ち）");
console.log("");
console.log("  上限  素数   決着率   平均手数   グラフ（決着率）");
for (let max = 3; max <= 40; max++) {
  const r = runMany({ max: max, strategy: "random", games: 5000, cap: 5000 });
  const bar = "#".repeat(Math.round(r.rate * 40));
  const mark = max === 5 ? " ←元ゲーム" : max === 31 ? " ←現状" : "";
  console.log("  " + String(max).padStart(3)
    + "  " + (isPrime(max) ? " ○ " : " · ")
    + "  " + (r.rate * 100).toFixed(1).padStart(6) + "%"
    + "  " + r.avg.toFixed(1).padStart(7) + "手"
    + "   " + bar + mark);
}
console.log("");
console.log("  ※素数の列を出したのは「素数だと決着しやすいのでは」と考えたから。");
console.log("    データは支持しなかったので、仮説は捨てた。");
console.log("    シミュレーションは“自分が正しいと証明する道具”ではなく、");
console.log("    “自分が間違っていたら教えてくれる道具”。");

// ---- パート3：100%が本物か -------------------------------------------
console.log("");
console.log("");
console.log("■ パート3：100%は本物か（各5万回・打ち切り20,000手）");
console.log("");
for (const [label, max] of [
  ["上限7  （100%だった）", 7],
  ["上限14 （100%だった）", 14],
  ["上限23 （100%だった）", 23],
  ["上限27 （100%だった）", 27],
  ["上限15 （89%だった）",  15],
  ["上限31 （現状）",       31],
]) {
  line(label, runMany({ max: max, strategy: "random", games: 50000, cap: 20000 }));
}
